**Kode Program PHP**

```php
<?php
$x = 15;
$y = 4;

echo "x = $x<br>";
echo "y = $y<br><br>";

echo "Penjumlahan (15 + 4) = " . ($x + $y) . "<br>";
echo "Pengurangan (15 - 4) = " . ($x - $y) . "<br>";
echo "Perkalian (15 * 4) = " . ($x * $y) . "<br>";
echo "Pembagian (15 / 4) = " . ($x / $y) . "<br>";
echo "Modulus (15 % 4) = " . ($x % $y) . "<br>";
echo "Pangkat (15 ** 4) = " . ($x ** $y);
?>
```

**Hasil output:**

```text
x = 15
y = 4

Penjumlahan (15 + 4) = 19
Pengurangan (15 - 4) = 11
Perkalian (15 * 4) = 60
Pembagian (15 / 4) = 3.75
Modulus (15 % 4) = 3
Pangkat (15 ** 4) = 50625
```
